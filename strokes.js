// Generator for Yōon (contracted sounds)
// -----------------------------------------------------------------------------

function synthesizeYoon(baseCh, smallCh, isKata) {
  const base = STROKES[baseCh];
  const small = (isKata ? SMALL_KATA : SMALL_HIRA)[smallCh];
  if (!base || !small) return null;

  const combined = base.map(stroke => stroke.map(pt => [...pt]));

  const scale = 0.55;
  const offsetX = 45;
  const offsetY = 35;

  small.forEach(stroke => {
    combined.push(stroke.map(pt => [
      pt[0] * scale + offsetX,
      pt[1] * scale + offsetY
    ]));
  });

  return combined;
}

