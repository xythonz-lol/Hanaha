// Generates a voiced character by appending the marks to the base character
function addDakuten(base, isHandakuten = false) {
  const baseStrokes = STROKES[base];
  if (!baseStrokes) return null;
  
  // Deep copy base strokes
  const newStrokes = baseStrokes.map(s => s.map(p => [...p]));
  const marks = isHandakuten ? HANDAKUTEN : DAKUTEN;
  
  marks.forEach(mark => {
    newStrokes.push(mark.map(p => [...p]));
  });
  
  return newStrokes;
}

